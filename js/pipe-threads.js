const pipeMm = inches => inches == null ? null : inches * 25.4;
const pipeRange = (min, max) => [pipeMm(min), pipeMm(max)];

function pipeDimensions(table, row) {
  switch (table) {
    case 2: {
      const h = row[21];
      return {
        external: {major: pipeRange(row[4] + h, row[4] + h), pitch: pipeRange(row[4], row[4]), minor: pipeRange(row[23], row[23])},
        internal: {major: pipeRange(row[7] + h, row[7] + h), pitch: pipeRange(row[7], row[7]), minor: pipeRange(row[7] - h, row[7] - h)},
      };
    }
    case 4:
      return {internal: {minor: pipeRange(row[3], null), pitch: pipeRange(row[4], row[5])}};
    case 5: {
      const npt = PIPE_NPT_BY_SIZE.get(row[0]);
      return {
        external: {major: pipeRange(row[4] + row[3], row[4] + row[3]), pitch: pipeRange(row[4], row[4]), minor: pipeRange(row[4] - row[3], row[4] - row[3])},
        internal: pipeDimensions(2, npt).internal,
      };
    }
    case 6:
      return {
        external: {major: pipeRange(row[5], row[4]), pitch: pipeRange(row[7], row[6])},
        internal: {minor: pipeRange(row[8], row[9]), pitch: pipeRange(row[10], row[11])},
      };
    case 7:
      return {
        external: {major: pipeRange(null, row[3]), pitch: pipeRange(row[5], row[4])},
        internal: {minor: pipeRange(row[6], null), pitch: pipeRange(row[7], row[8])},
      };
  }
}

