function pipeMeasureInfo(thread, side) {
  const [min, max] = thread.pipe[side][side === 'external' ? 'major' : 'minor'];
  const ref = min == null ? max : max == null ? min : (min + max) / 2;
  return {ref, range: !thread.taper && min != null && max != null ? [min, max] : null};
}
